/** Случайная цитата, отличная от предыдущей (если передана). */
export function pickQuote(previousText = '') {
  const pool = QUOTES.filter((quote) => quote.text !== previousText);
  const list = pool.length ? pool : QUOTES;
  return list[Math.floor(Math.random() * list.length)];
}
